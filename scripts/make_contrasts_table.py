"""Build tables/tab_luad_contrasts.tex from data/luad_hierarchical_contrasts.csv.

Every deciding contrast of the regime rule (PI-B2, FC-B2, FC-PI) and the
vocabulary-omission contrast (B3-B2), for all six genes under both outer
protocols, with its hierarchical-bootstrap 95% interval and the number of
seeds on which the point contrast is positive. The CSV is the one that
tab_mutation_luad.tex reads its B3-B2 rows from, so the two tables cannot
disagree.

Run from paper1_medical/:  python scripts/make_contrasts_table.py
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "luad_hierarchical_contrasts.csv"
OUT = ROOT / "tables" / "tab_luad_contrasts.tex"

GENES = ["TP53", "EGFR", "STK11", "KEAP1", "KRAS", "RBM10"]
CONTRASTS = ["PI-B2", "FC-B2", "FC-PI", "B3-B2"]
HEAD = {
    "PI-B2": r"$\mathrm{PI}-\mathrm{B2}$",
    "FC-B2": r"$\mathrm{FC}-\mathrm{B2}$",
    "FC-PI": r"$\mathrm{FC}-\mathrm{PI}$",
    "B3-B2": r"$\mathrm{B3}-\mathrm{B2}$",
}
CLAIM = {
    "PI-B2": "(ii-a) additive",
    "FC-B2": "equivalence, (i)/(iii)",
    "FC-PI": "(ii-b) non-additive",
    "B3-B2": "what the vocabulary omits",
}
PROTO = {"patient": "Patient-preserved outer folds",
         "site": "Site-preserved outer folds, site-clustered bootstrap"}
MARGIN = 0.02


def fmt(x: float) -> str:
    s = f"{x:+.3f}".replace("0.", ".", 1) if abs(x) < 1 else f"{x:+.3f}"
    return s.replace("-", "$-$").replace("+", "$+$")


def cell(row: pd.Series) -> str:
    lo, hi = row.ci_lo, row.ci_hi
    excl = lo > 0 or hi < 0
    equiv = lo > -MARGIN and hi < MARGIN
    point = fmt(row.point)
    if excl:
        point = r"\textbf{" + point + "}"
    if equiv:
        point += r"\textsuperscript{$\approx$}"
    seeds = f"{int(row.positive_seeds)}/{int(row.n_seeds)}"
    return (f"{point} {{\\scriptsize[{fmt(lo)},\\,{fmt(hi)}]}}"
            f" {{\\scriptsize {seeds}}}")


def main() -> None:
    df = pd.read_csv(SRC)
    lines = [
        "% Generated by scripts/make_contrasts_table.py from",
        "% data/luad_hierarchical_contrasts.csv. Do not edit by hand.",
        r"\resizebox{\linewidth}{!}{%",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\renewcommand{\arraystretch}{1.2}",
        r"\begin{tabular}{l l l l l}",
        r"\toprule",
        r"\textbf{Gene} & " + " & ".join(r"\textbf{" + HEAD[c] + "}"
                                        for c in CONTRASTS) + r" \\",
        " & " + " & ".join(r"{\scriptsize " + CLAIM[c] + "}"
                           for c in CONTRASTS) + r" \\",
        r"\midrule",
    ]
    for proto, title in PROTO.items():
        lines.append(r"\multicolumn{5}{l}{\textbf{" +
                     ("a" if proto == "patient" else "b") + "}, " + title +
                     r"}\\")
        lines.append(r"\addlinespace[1pt]")
        sub = df[df.protocol == proto].set_index(["gene", "contrast"])
        for g in GENES:
            cells = [cell(sub.loc[(g, c)]) for c in CONTRASTS]
            lines.append(r"\textit{" + g + "} & " + " & ".join(cells) +
                         r" \\")
        if proto == "patient":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}%", "}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    n_excl = int(((df.ci_lo > 0) | (df.ci_hi < 0)).sum())
    n_equiv = int(((df.ci_lo > -MARGIN) & (df.ci_hi < MARGIN)).sum())
    print(f"wrote {OUT.name}: {len(df)} contrasts, {n_excl} exclude zero, "
          f"{n_equiv} inside the ±{MARGIN} equivalence margin")
    print(df[(df.ci_lo > 0) | (df.ci_hi < 0)][
        ["protocol", "gene", "contrast", "point", "ci_lo", "ci_hi"]])
    print(df[(df.ci_lo > -MARGIN) & (df.ci_hi < MARGIN)][
        ["protocol", "gene", "contrast", "point", "ci_lo", "ci_hi"]])


if __name__ == "__main__":
    main()
